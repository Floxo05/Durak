export const DICTS: Record<Lang, Dict> = { de, fr, en };
export const LANGS: { id: Lang; flag: string; label: string }[] = [
  { id: 'de', flag: '🇩🇪', label: 'Deutsch' },
  { id: 'fr', flag: '🇫🇷', label: 'Français' },
  { id: 'en', flag: '🇬🇧', label: 'English' },
];

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem('durak.lang') as Lang | null;
    if (saved && saved in DICTS) return saved;
  } catch {
    /* ignore */
  }
  const nav = (navigator.language || 'de').slice(0, 2);
  return nav === 'fr' ? 'fr' : nav === 'en' ? 'en' : 'de';
}

export type TFn = (key: string, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): TFn {
  const d = DICTS[lang];
  return (key, vars) => {
    let s = d[key] ?? DICTS.de[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

export const I18nContext = createContext<{ lang: Lang; t: TFn; setLang: (l: Lang) => void }>({
  lang: 'de',
  t: makeT('de'),
  setLang: () => {},
});
export const useI18n = () => useContext(I18nContext);
